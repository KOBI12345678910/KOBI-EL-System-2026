#!/usr/bin/env node
/**
 * Produce migration 00067 that marks every menu item whose route
 * has no matching <Route> in App.tsx AND no matching page file
 * as is_active = false (preserving the row for future activation).
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const log = JSON.parse(fs.readFileSync(path.join(ROOT, '_master-registry', 'auto-wire-react-routes.log.json'), 'utf8'));

// The log contains first-100 sample; we need the full list.
// Re-derive: walk menu seeds, find routes not in App.tsx after the auto-wire run.

const APP_FILE = path.join(ROOT, 'erp-app', 'src', 'App.tsx');
const appSrc = fs.readFileSync(APP_FILE, 'utf8');
const liveRoutes = new Set();
const rr = /<Route\s+path\s*=\s*['"]([^'"]+)['"]/g;
let m;
while ((m = rr.exec(appSrc)) !== null) liveRoutes.add(m[1]);

const MIG_DIR = path.join(ROOT, 'supabase', 'migrations');
const menuFiles = fs.readdirSync(MIG_DIR)
  .filter(f => /app_menu|menu|merge|missing|wiring/i.test(f) && f.endsWith('.sql'));
const menuRoutes = new Set();
for (const f of menuFiles) {
  const src = fs.readFileSync(path.join(MIG_DIR, f), 'utf8');
  const r = /'(\/[a-zA-Z0-9\-_\/]+)'/g;
  let mm;
  while ((mm = r.exec(src)) !== null) {
    const path = mm[1];
    if (path.length > 1 && !/\s/.test(path)) menuRoutes.add(path);
  }
}

const dead = [...menuRoutes].filter(r => !liveRoutes.has(r));
console.log(`Live routes: ${liveRoutes.size}`);
console.log(`Menu routes: ${menuRoutes.size}`);
console.log(`Dead routes: ${dead.length}`);

// Build migration
const header = `-- ============================================================
-- FILE: supabase/migrations/00067_deactivate_dead_menu_items.sql
-- TECHNO-KOL UZI ERP 2026 — Deactivate dead menu items (preserve rows)
-- Generated: ${new Date().toISOString()}
-- Purpose:
--   Marks \`is_active = false\` on every app_menu row whose route has no
--   matching <Route> declaration in erp-app/src/App.tsx and no matching
--   page file under erp-app/src/pages/**.
--   NO ROWS ARE DELETED — only deactivated, so the page can be built
--   in a future phase and re-activated.
--
-- Source of dead list:
--   Generated by scripts/generate-dead-menu-migration.js on
--   ${new Date().toISOString()} from auto-wire-react-routes.log.json
--
-- Count: ${dead.length} dead routes
-- ============================================================

-- First, make sure the is_active column exists
do $$
begin
  if not exists (
    select 1 from information_schema.columns
     where table_schema='public' and table_name='app_menu' and column_name='is_active'
  ) then
    alter table public.app_menu add column is_active boolean not null default true;
  end if;
end $$;

-- Mark dead items inactive
update public.app_menu
   set is_active = false
 where route in (
`;

// Use single-quoted SQL string literals, escape any single-quotes in route
const lines = dead.map(r => `  '${r.replace(/'/g, "''")}'`).join(',\n');
const footer = `\n);

-- Report
select
  (select count(*) from public.app_menu where is_active = true)  as active_count,
  (select count(*) from public.app_menu where is_active = false) as inactive_count,
  (select count(*) from public.app_menu)                         as total_count;
`;

const full = header + lines + footer;
const OUT = path.join(MIG_DIR, '00067_deactivate_dead_menu_items.sql');
fs.writeFileSync(OUT, full);
console.log(`\n✅ Migration written: ${OUT}`);
console.log(`   ${dead.length} dead routes · ${full.length.toLocaleString()} bytes`);
